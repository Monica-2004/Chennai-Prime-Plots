"""Single generic LLM Client module for interacting with the local Ollama instance.

Communicates with Ollama running at http://localhost:11434 (default model 'qwen2.5:3b').
Designed to be generic so it can be reused across pipeline stages (Stage 2 Query Understanding,
Stage 5 Explainability).
"""

from typing import Any, Dict, Optional
import httpx
from backend.app.core.config import settings


class OllamaClientError(Exception):
    """Exception raised for Ollama communication or generation errors."""
    pass


class OllamaClient:
    """Client for local Ollama server running qwen2.5:3b."""

    def __init__(self, base_url: Optional[str] = None, model: Optional[str] = None):
        self.base_url = (base_url or settings.OLLAMA_BASE_URL).rstrip("/")
        self.model = model or settings.OLLAMA_MODEL
        self.timeout = settings.OLLAMA_TIMEOUT_SECONDS

    async def check_health(self) -> Dict[str, Any]:
        """Check if Ollama is accessible and whether the configured model is available."""
        async with httpx.AsyncClient(timeout=5.0) as client:
            try:
                response = await client.get(f"{self.base_url}/api/tags")
                response.raise_for_status()
                data = response.json()
                models = [m.get("name") for m in data.get("models", [])]
                model_found = any(self.model in m for m in models)
                return {
                    "status": "connected",
                    "model_available": model_found,
                    "available_models": models,
                }
            except Exception as e:
                return {
                    "status": "disconnected",
                    "error": str(e),
                    "model_available": False,
                }

    async def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        temperature: float = 0.0,
    ) -> str:
        """Send a prompt to Ollama /api/generate and return the raw text response.
        
        Args:
            prompt: Text prompt to provide to the model.
            system_prompt: Optional system instruction prompt.
            temperature: Sampling temperature (0.0 for deterministic output).

        Returns:
            The raw string response generated by the model.

        Raises:
            OllamaClientError: If connection fails or Ollama returns an error.
        """
        payload: Dict[str, Any] = {
            "model": self.model,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": temperature,
            },
        }
        if system_prompt:
            payload["system"] = system_prompt

        async with httpx.AsyncClient(timeout=self.timeout) as client:
            try:
                response = await client.post(
                    f"{self.base_url}/api/generate",
                    json=payload,
                )
                response.raise_for_status()
                data = response.json()
                return data.get("response", "")
            except httpx.ConnectError as e:
                raise OllamaClientError(
                    f"Unable to connect to Ollama at {self.base_url}. Ensure Ollama is running."
                ) from e
            except httpx.HTTPStatusError as e:
                raise OllamaClientError(
                    f"Ollama returned HTTP error {e.response.status_code}: {e.response.text}"
                ) from e
            except Exception as e:
                raise OllamaClientError(f"Unexpected error communicating with Ollama: {str(e)}") from e


# Singleton instance
llm_client = OllamaClient()
