"""Stage 8: Full Report Mode

Generates a complete, comprehensive analytical report for any ingested dataset without
requiring manual query-by-query prompts.

Sections:
1. Dataset Overview: schema, row/column counts, types, missing values, source_type
2. Descriptive Statistics: numeric distributions (mean, median, min, max, std) & category frequencies
3. Auto-Generated Key Insights: verified deterministically via Stage 3 execution and Stage 4 verification
4. Visual Charts: bar and line chart specifications adhering to Stage 6 format
5. Plain-Language Executive Summary: generated by Ollama qwen2.5:3b strictly grounded in verified facts
6. Document Notes: qualitative summaries for PDF/PPTX unstructured text clearly flagged as unverified
"""

from typing import Any, Dict, List, Optional, Tuple
import numpy as np
import pandas as pd

from backend.app.core.llm_client import llm_client, OllamaClient
from backend.app.models.schemas import (
    DatasetMetadata,
    QueryIntent,
    KeyInsightItem,
    ReportSection,
    ReportResponse,
)
from backend.app.pipeline.stage1_ingestion import ingestion_service, DataIngestionService
from backend.app.pipeline.stage3_analyst_agent import analyst_agent, AIAnalystAgent
from backend.app.pipeline.stage4_verification import verification_layer, VerificationLayer


class ReportGenerator:
    """Orchestrates comprehensive automated report generation."""

    def __init__(
        self,
        ingestion: Optional[DataIngestionService] = None,
        analyst: Optional[AIAnalystAgent] = None,
        verifier: Optional[VerificationLayer] = None,
        client: Optional[OllamaClient] = None,
    ):
        self.ingestion = ingestion or ingestion_service
        self.analyst = analyst or analyst_agent
        self.verifier = verifier or verification_layer
        self.llm = client or llm_client

    async def generate_report(self, session_id: str) -> ReportResponse:
        """Generate a complete structured report for a loaded dataset session.

        Args:
            session_id: Active dataset session/file ID.

        Returns:
            ReportResponse with overview, stats, verified insights, charts, narrative, and sections.
        """
        if not session_id:
            raise ValueError("session_id must be provided to generate a report.")

        df = self.ingestion.load_dataset(session_id)
        metadata = self.ingestion.get_metadata(session_id)

        if metadata is None:
            raise KeyError(f"Metadata for session '{session_id}' not found.")

        # 1. Dataset Overview
        overview = self._build_overview(df, metadata)

        # 2. Descriptive Statistics
        stats = self._build_descriptive_stats(df)

        # 3. Auto-Generated Key Insights (Stage 3 + Stage 4 verified)
        insights, charts = self._build_key_insights_and_charts(df, metadata)

        # 4. Document Notes for Unstructured Content (if PDF/PPTX text present)
        doc_notes = await self._build_document_notes(metadata)

        # 5. Plain-Language Executive Summary (grounded LLM narrative)
        narrative = await self._generate_executive_narrative(
            metadata=metadata,
            overview=overview,
            stats=stats,
            insights=insights,
            doc_notes=doc_notes,
        )

        # 6. Structured Sections Array for frontend consumption
        sections: List[ReportSection] = [
            ReportSection(type="overview", title="Dataset Overview", data=overview),
            ReportSection(type="stat", title="Descriptive Statistics", data=stats),
            ReportSection(type="insight", title="Key Verified Insights", data=[i.model_dump() for i in insights]),
            ReportSection(type="chart", title="Visual Analysis", data=charts),
            ReportSection(type="narrative", title="Executive Summary", data={"narrative": narrative}),
        ]

        if doc_notes:
            sections.append(
                ReportSection(type="document_notes", title="Document Notes (Unstructured)", data=doc_notes)
            )

        all_verified = all(i.verified for i in insights) if insights else True

        return ReportResponse(
            session_id=session_id,
            dataset_overview=overview,
            descriptive_statistics=stats,
            key_insights=insights,
            charts=charts,
            narrative_summary=narrative,
            document_notes=doc_notes,
            sections=sections,
            all_insights_verified=all_verified,
        )

    def _build_overview(self, df: pd.DataFrame, metadata: DatasetMetadata) -> Dict[str, Any]:
        """Synthesize high-level dataset profiling and structural metadata."""
        col_types = {col: str(df[col].dtype) for col in df.columns} if not df.empty else {}
        missing_dict = {col: int(df[col].isna().sum()) for col in df.columns} if not df.empty else {}

        return {
            "filename": metadata.filename,
            "source_type": metadata.source_type,
            "row_count": len(df),
            "column_count": len(df.columns),
            "data_types": col_types,
            "missing_values": missing_dict,
            "has_structured_tables": metadata.has_structured_tables,
            "has_unstructured_text": metadata.has_unstructured_text,
            "warning": metadata.warning,
        }

    def _build_descriptive_stats(self, df: pd.DataFrame) -> Dict[str, Any]:
        """Compute statistical measures across numeric and categorical columns."""
        if df.empty:
            return {"numeric_columns": {}, "categorical_columns": {}}

        numeric_stats: Dict[str, Dict[str, Any]] = {}
        categorical_stats: Dict[str, Dict[str, Any]] = {}

        # Numeric Columns Profiling
        numeric_cols = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]
        for col in numeric_cols:
            series = df[col].dropna()
            if len(series) > 0:
                mean_val = round(float(series.mean()), 2)
                median_val = round(float(series.median()), 2)
                min_val = round(float(series.min()), 2)
                max_val = round(float(series.max()), 2)
                std_val = round(float(series.std()), 2) if len(series) > 1 else 0.0
                numeric_stats[col] = {
                    "mean": mean_val,
                    "median": median_val,
                    "min": min_val,
                    "max": max_val,
                    "std": std_val,
                    "count": int(len(series)),
                    "missing": int(df[col].isna().sum()),
                }

        # Categorical Columns Profiling
        cat_cols = [c for c in df.columns if c not in numeric_cols]
        for col in cat_cols:
            series = df[col].dropna()
            val_counts = series.value_counts().head(5).to_dict()
            top_cats = [{"category": str(k), "count": int(v)} for k, v in val_counts.items()]
            categorical_stats[col] = {
                "unique_count": int(series.nunique()),
                "top_categories": top_cats,
                "missing": int(df[col].isna().sum()),
            }

        return {
            "numeric_columns": numeric_stats,
            "categorical_columns": categorical_stats,
        }

    def _build_key_insights_and_charts(
        self,
        df: pd.DataFrame,
        metadata: DatasetMetadata,
    ) -> Tuple[List[KeyInsightItem], List[Dict[str, Any]]]:
        """Generate automated key aggregations strictly using Stage 3 execution and Stage 4 verification."""
        if df.empty or len(df.columns) == 0:
            return [], []

        insights: List[KeyInsightItem] = []
        charts: List[Dict[str, Any]] = []

        numeric_cols = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]
        cat_cols = [c for c in df.columns if not pd.api.types.is_numeric_dtype(df[c])]

        # Identify date/time column if present
        date_col = next(
            (c for c in df.columns if any(kw in c.lower() for kw in ("date", "month", "year", "time", "day"))),
            None,
        )

        # Primary categorical entity column (e.g. product_name, item, customer)
        entity_col = None
        for c in cat_cols:
            if c != date_col:
                entity_col = c
                break

        # Group/category column (e.g. category, department, region)
        group_col = None
        for c in cat_cols:
            if c != entity_col and c != date_col:
                group_col = c
                break

        # If only one categorical column exists
        if not group_col and entity_col:
            group_col = entity_col

        # 1. Max Value Ranking per Numeric Column (e.g. Top product by revenue)
        if numeric_cols and entity_col:
            for num_col in numeric_cols[:2]:  # Focus on top 2 metrics
                intent = QueryIntent(
                    raw_query=f"Highest {num_col} by {entity_col}",
                    operation="max",
                    target_column=num_col,
                    group_by_column=entity_col,
                )
                analyst_res = self.analyst.execute(df, intent)
                verification = self.verifier.verify(df, intent, analyst_res)

                if analyst_res.success and analyst_res.result_value:
                    res_val = analyst_res.result_value
                    entity_name = res_val.get(entity_col, "Unknown") if isinstance(res_val, dict) else str(res_val)
                    val_amt = res_val.get(num_col, 0) if isinstance(res_val, dict) else res_val

                    insight_text = (
                        f"The {entity_col.replace('_', ' ')} with the highest {num_col.replace('_', ' ')} "
                        f"is {entity_name} with {val_amt:,}."
                        if isinstance(val_amt, (int, float))
                        else f"Highest {num_col} is {val_amt}."
                    )

                    chart_spec = None
                    if analyst_res.result_table and len(analyst_res.result_table) >= 2:
                        chart_spec = {
                            "chart_type": "bar",
                            "title": f"Top {num_col.replace('_', ' ').title()} by {entity_col.replace('_', ' ').title()}",
                            "x_key": entity_col,
                            "y_key": num_col,
                            "data": analyst_res.result_table,
                        }
                        charts.append(chart_spec)

                    insights.append(
                        KeyInsightItem(
                            title=f"Top {entity_col.replace('_', ' ').title()} by {num_col.replace('_', ' ').title()}",
                            operation="max",
                            target_column=num_col,
                            group_by_column=entity_col,
                            result_value=val_amt,
                            insight_text=insight_text,
                            verified=verification.verified,
                            verification_status=verification.status,
                            discrepancy=verification.discrepancy,
                            chart=chart_spec,
                        )
                    )

        # 2. Category Aggregation / Breakdown (e.g. Revenue by Category)
        if numeric_cols and group_col:
            target_num = numeric_cols[0]
            intent = QueryIntent(
                raw_query=f"Total {target_num} by {group_col}",
                operation="sum",
                target_column=target_num,
                group_by_column=group_col,
            )
            analyst_res = self.analyst.execute(df, intent)
            verification = self.verifier.verify(df, intent, analyst_res)

            if analyst_res.success and analyst_res.result_table:
                chart_spec = {
                    "chart_type": "bar",
                    "title": f"Total {target_num.replace('_', ' ').title()} by {group_col.replace('_', ' ').title()}",
                    "x_key": group_col,
                    "y_key": target_num,
                    "data": analyst_res.result_table,
                }
                charts.append(chart_spec)

                insights.append(
                    KeyInsightItem(
                        title=f"{target_num.replace('_', ' ').title()} Breakdown by {group_col.replace('_', ' ').title()}",
                        operation="sum",
                        target_column=target_num,
                        group_by_column=group_col,
                        result_value=analyst_res.result_value,
                        insight_text=f"Total {target_num.replace('_', ' ')} breakdown computed across {len(analyst_res.result_table)} {group_col.replace('_', ' ')} segments.",
                        verified=verification.verified,
                        verification_status=verification.status,
                        discrepancy=verification.discrepancy,
                        chart=chart_spec,
                    )
                )

        # 3. Time-Based Trend (e.g. Revenue Trend by Month)
        if date_col and numeric_cols:
            target_num = numeric_cols[0]
            intent = QueryIntent(
                raw_query=f"Total {target_num} by {date_col}",
                operation="sum",
                target_column=target_num,
                group_by_column=date_col,
            )
            analyst_res = self.analyst.execute(df, intent)
            verification = self.verifier.verify(df, intent, analyst_res)

            if analyst_res.success and analyst_res.result_table:
                chart_spec = {
                    "chart_type": "line",
                    "title": f"{target_num.replace('_', ' ').title()} Trend over {date_col.replace('_', ' ').title()}",
                    "x_key": date_col,
                    "y_key": target_num,
                    "data": analyst_res.result_table,
                }
                charts.append(chart_spec)

                insights.append(
                    KeyInsightItem(
                        title=f"{target_num.replace('_', ' ').title()} Trend over Time",
                        operation="sum",
                        target_column=target_num,
                        group_by_column=date_col,
                        result_value=analyst_res.result_value,
                        insight_text=f"Tracked {target_num.replace('_', ' ')} progression across time periods in '{date_col}'.",
                        verified=verification.verified,
                        verification_status=verification.status,
                        discrepancy=verification.discrepancy,
                        chart=chart_spec,
                    )
                )

        return insights, charts

    async def _build_document_notes(self, metadata: DatasetMetadata) -> Optional[Dict[str, Any]]:
        """Summarize unstructured text from PDF/PPTX with clear qualitative / unverified caveats."""
        if not metadata.has_unstructured_text or not metadata.unstructured_text:
            return None

        raw_text = metadata.unstructured_text[:2000]  # Cap length for prompt safety

        prompt = f"""Summarize the following document excerpt into 2-3 clear, objective sentences:

Document Excerpt:
{raw_text}

Provide ONLY the concise summary:"""

        system_prompt = (
            "You are an assistant summarizing qualitative document notes. "
            "Write 2-3 objective, neutral sentences without exaggeration."
        )

        try:
            summary = await self.llm.generate(prompt=prompt, system_prompt=system_prompt)
            summary_clean = summary.strip()
        except Exception:
            summary_clean = raw_text[:300] + "..."

        return {
            "source_type": metadata.source_type,
            "summary": summary_clean,
            "raw_text_snippet": raw_text[:500],
            "is_verified": False,
            "disclaimer": (
                "Qualitative notes extracted from unstructured document text. "
                "These insights are unverified and not derived from structured tabular data."
            ),
        }

    async def _generate_executive_narrative(
        self,
        metadata: DatasetMetadata,
        overview: Dict[str, Any],
        stats: Dict[str, Any],
        insights: List[KeyInsightItem],
        doc_notes: Optional[Dict[str, Any]],
    ) -> str:
        """Generate a short 3-5 sentence overall narrative tying the verified facts together using Ollama."""
        # 1. Edge Case: Unstructured Text Only
        if not metadata.has_structured_tables and doc_notes:
            return (
                f"The ingested document '{metadata.filename}' ({metadata.source_type.upper()}) contains unstructured text rather than structured data tables. "
                f"Key qualitative points noted: {doc_notes['summary']} "
                f"Note: Quantitative table queries cannot be executed against this source."
            )

        # 2. Gather factual figures strictly for prompt grounding
        facts = [
            f"Dataset filename: '{metadata.filename}' ({metadata.source_type.upper()})",
            f"Total rows: {overview['row_count']}, columns: {overview['column_count']}",
        ]

        # Numeric stats facts
        num_stats = stats.get("numeric_columns", {})
        for col, s in list(num_stats.items())[:2]:
            facts.append(
                f"Metric '{col}': mean={s['mean']}, median={s['median']}, min={s['min']}, max={s['max']}"
            )

        # Key insights facts
        for item in insights:
            facts.append(f"Verified Insight ({item.title}): {item.insight_text}")

        facts_block = "\n".join(f"- {f}" for f in facts)

        prompt = f"""Write an executive report summary (3-5 sentences) based strictly on these verified facts:

{facts_block}

Requirements:
- Exactly 3 to 5 sentences.
- Plain language for business stakeholders.
- Mention key verified numbers directly from the facts above.
- Do NOT invent any numbers, percentages, dates, or causes not provided."""

        system_prompt = (
            "You are an expert financial and data analyst writing an executive report summary. "
            "CRITICAL: Rely ONLY on the verified factual figures provided. "
            "Never invent, assume, or hallucinate metrics, dates, or facts."
        )

        try:
            narrative = await self.llm.generate(prompt=prompt, system_prompt=system_prompt)
            cleaned = narrative.strip().replace('"', '')
            if len(cleaned) > 20:
                return cleaned
        except Exception:
            pass

        # Robust deterministic fallback if LLM is unavailable
        insight_sentences = " ".join(item.insight_text for item in insights[:2])
        return (
            f"Analysis of dataset '{metadata.filename}' ({overview['row_count']} records) completed successfully. "
            f"{insight_sentences} "
            f"All findings have been independently verified against the underlying source data."
        )


# Global ReportGenerator instance
report_generator = ReportGenerator()
